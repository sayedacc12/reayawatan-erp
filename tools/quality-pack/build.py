def sec(title, body):
    return {'title': title, 'body': body.strip()}


def bullets(items):
    return '\n'.join(f'• {x}' for x in items)


def numbered(items):
    return '\n'.join(f'{i + 1}. {x}' for i, x in enumerate(items))


def doc(code, doc_type, dept, title, iso, sections, owner, related=(), retention=None, summary=DRAFT_NOTE):
    return {
        'code': code, 'docType': doc_type, 'department': dept, 'title': title, 'isoClauses': list(iso),
        'ownerName': owner, 'sections': sections, 'relatedCodes': [c for c in dict.fromkeys(related) if c != code],
        'retention': retention, 'changeSummary': summary,
    }


def write(name, pack):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), 'w', encoding='utf-8') as f:
        json.dump(pack, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print(name, len(pack['documents']), 'documents', len(pack['maps']), 'maps')


