RACI = {'R': 'ينفذ', 'A': 'يعتمد ويُسأل', 'C': 'يُستشار', 'I': 'يُبلَّغ'}
KIND = {'start': 'start', 'end': 'end', 'task': 'task', 'decision': 'decision', 'document': 'document', 'system': 'task'}


def raci_text(rows):
    out = []
    for activity, roles in rows:
        who = '، '.join(f'{role} ({" و".join(RACI[c] for c in letters if c in RACI)})' for role, letters in roles.items())
        out.append(f'• {activity}: {who}')
    return '\n'.join(out)


def steps_text(steps):
    out, n = [], 0
    for s in steps:
        if s['kind'] == 'start':
            out.append(f'البداية: {s["label"]}')
            continue
        if s['kind'] == 'end':
            out.append(f'النهاية: {s["label"]}')
            continue
        n += 1
        line = f'{n}. {s["label"]}'
        who = s.get('who')
        if who:
            line += f' ({who})'
        parts = [line]
        if s.get('screen') and s['screen'] != '-':
            parts.append(f'   الشاشة: {s["screen"]}')
        if s.get('detail'):
            parts.append(f'   {s["detail"]}')
        if s['kind'] == 'decision' and s.get('next'):
            parts.append('   المسارات: ' + '، '.join(x[1] for x in s['next'] if isinstance(x, (list, tuple))))
        if s.get('form'):
            parts.append(f'   النموذج: {s["form"]}')
        if s.get('out'):
            parts.append(f'   المخرج: {s["out"]}')
        out.append('\n'.join(parts))
    return '\n'.join(out)


