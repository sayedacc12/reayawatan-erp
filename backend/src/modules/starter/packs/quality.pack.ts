/** الجودة ISO 9001: سياق الشركة (القضايا والأطراف المعنية والعمليات والمسؤوليات) ومسودة سياسة الجودة */
@Injectable()
export class QualityStarter implements StarterPack {
  readonly module = 'quality';
  readonly steps: StarterStep[];

  constructor(private readonly core: QmsCore) {
    this.steps = [
      {
        key: 'context', label: 'سياق الشركة وسياسة الجودة',
        detail: 'القضايا الداخلية والخارجية، والأطراف المعنية واحتياجاتها، والعمليات الرئيسية ومؤشراتها، والمسؤوليات، ومسودة سياسة جودة تعتمدها الإدارة. تُملأ الأقسام الفارغة فقط.',
        run: async (a) => {
          const c = await this.core.getContext(a);
          let n = 0;
          const fill = <T>(cur: T[], def: T[]) => (cur.length ? cur : (n += def.length, def));
          const next = {
            ...c,
            issues: fill(c.issues, ISSUES),
            parties: fill(c.parties, PARTIES),
            processes: fill(c.processes, PROCESSES),
            responsibilities: fill(c.responsibilities, RESPONSIBILITIES),
            // مسودة بلا اعتماد: تعتمدها الإدارة بعد مراجعتها
            policy: c.policy.text ? c.policy : (n++, { text: POLICY, approvedBy: '', date: null }),
          };
          if (!n) return existing('أقسام السياق مكتملة');
          await this.core.saveContext(a, { context: next as never });
          return added(n);
        },
      },
    ];
  }
}
