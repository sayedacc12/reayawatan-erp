/** طول الرقم في كل مستوى: المستوى 1 رقم واحد ... المستوى 6 عشرة أرقام */
const LEN_BY_LEVEL = [0, 1, 2, 3, 5, 8, 10];
/** ما يُضاف للرقم عند النزول مستوى بحساب «بنفس الاسم» */
const PAD_SUFFIX: Record<number, string> = { 1: '1', 2: '1', 3: '01', 4: '001', 5: '01' };

export interface CoaAccount {
  code: string;
  name: string;
  level: number;
  parentCode: string | null;
  kind: 'root' | 'main' | 'sub';
  nature: CoaNature;
}

const levelOf = (code: string) => LEN_BY_LEVEL.indexOf(code.length);

function natureOf(code: string): CoaNature {
  if (code[0] === '1') return 'assets';
  if (code[0] === '3') return 'revenue';
  if (code[0] === '4') return 'expenses';
  return code.startsWith('23') ? 'net_assets' : 'liabilities';
}

/** الدليل كاملًا مرتبًا (الأب قبل الابن)، والحسابات الفرعية كلها في المستوى السادس */
export function buildCompanyChart(): CoaAccount[] {
  const names = new Map<string, string>();
  for (const line of RAW.split('\n')) {
    const [code, name] = line.split('|').map((s) => s?.trim());
    if (!code) continue;
    if (levelOf(code) < 1) throw new Error(`رقم حساب غير صالح في الدليل: ${code}`);
    if (names.has(code)) throw new Error(`رقم حساب مكرر في الدليل: ${code}`);
    names.set(code, name);
  }
  const parentOf = (code: string) => {
    const lvl = levelOf(code);
    return lvl > 1 ? code.slice(0, LEN_BY_LEVEL[lvl - 1]) : null;
  };
  for (const code of names.keys()) {
    const p = parentOf(code);
    if (p && !names.has(p)) throw new Error(`الحساب ${code} بلا أب (${p}) في الدليل`);
  }
  // استكمال الحسابات غير المفصلة حتى المستوى السادس بحساب بنفس الاسم
  const hasChild = new Set([...names.keys()].map(parentOf).filter(Boolean) as string[]);
  for (const code of [...names.keys()]) {
    if (hasChild.has(code)) continue;
    let c = code;
    while (levelOf(c) < COA_POSTING_LEVEL) {
      const next = c + PAD_SUFFIX[levelOf(c)];
      names.set(next, names.get(code)!);
      c = next;
    }
  }
  return [...names.keys()].sort().map((code) => {
    const level = levelOf(code);
    return {
      code, name: names.get(code)!, level, parentCode: parentOf(code), nature: natureOf(code),
      kind: level === 1 ? 'root' : level === COA_POSTING_LEVEL ? 'sub' : 'main',
    };
  });
}

