/** دمج الإعدادات المحفوظة مع الافتراضية (لأي حقل أُضيف لاحقًا) */
export function mergeConfig(saved: Partial<RiskConfig> | null | undefined): RiskConfig {
  const d = defaultConfig();
  const s = saved ?? {};
  return { ...d, ...s, workflows: { ...d.workflows, ...(s.workflows ?? {}) } };
}

